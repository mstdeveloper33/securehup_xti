    def test_v29_requires_explicit_migration_and_creates_empty_progress(self):
        repository = SQLiteAssetRepository(self.path)
        before = self.path.read_bytes()
        with self.assertRaises(StorageError):
            repository.inspect()
        self.assertEqual(self.path.read_bytes(), before)
        report = repository.migrate()
        self.assertEqual(
            (report["from_version"], report["to_version"]), (29, SCHEMA_VERSION),
        )
        self.assertTrue(report["changed"])
        self.assertTrue(Path(report["backup"]).is_file())
        inspected = repository.inspect()
        self.assertEqual(inspected["nvd_window_sync_count"], 0)
        with closing(sqlite3.connect(self.path)) as connection:
            version = connection.execute("PRAGMA user_version").fetchone()[0]
        self.assertEqual(version, SCHEMA_VERSION)

    def test_failed_creation_rolls_back_and_keeps_recovery_snapshot(self):
        repository = SQLiteAssetRepository(self.path)

        def incomplete(connection):
            connection.execute("CREATE TABLE nvd_window_syncs (unexpected TEXT NOT NULL)")
            raise sqlite3.OperationalError("controlled failure")

        with patch(
            "xti.adapters.sqlite.create_nvd_window_schema", side_effect=incomplete,
        ):
            with self.assertRaises(StorageError):
                repository.migrate()
        with closing(sqlite3.connect(self.path)) as connection:
            version = connection.execute("PRAGMA user_version").fetchone()[0]
            table = connection.execute(
                "SELECT name FROM sqlite_schema WHERE name = 'nvd_window_syncs'"
            ).fetchone()
        self.assertEqual(version, 29)
        self.assertIsNone(table)
        backups = list((self.path.parent / "backups").glob("*.db"))
        self.assertEqual(len(backups), 1)
        with closing(sqlite3.connect(backups[0])) as connection:
            self.assertEqual(connection.execute("PRAGMA user_version").fetchone()[0], 29)


