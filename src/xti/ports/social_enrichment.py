"""Provider I/O and durable submission boundaries for supplemental evidence."""
from typing import Protocol


class SocialProviderError(Exception):
    def __init__(self, code):
        self.code = code
        super().__init__(code)


class SocialProfileProvider(Protocol):
    def ready(self) -> None: ...
    def submit(self, targets: list[str]) -> str: ...
    def collect(self, snapshot: str, targets: list[str], domain: str) -> dict: ...


class SocialEnrichmentRepository(Protocol):
    def discovery(self, identifier: str) -> dict: ...
    def find(self, scope: dict, key: str) -> dict | None: ...
    def reserve(self, scope: dict, key: str, at: str, daily_limit: int) -> dict: ...
    def update(self, record: dict, state: dict, at: str) -> dict: ...
    def show(self, identifier: str) -> dict: ...
    def list(self, **options) -> dict: ...
