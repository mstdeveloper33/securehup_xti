"""Atomic scoped journal and source resolution boundaries."""
from typing import Protocol


class InvestigationRepository(Protocol):
    def catalog(self) -> dict: ...
    def propose(self, proposal: dict, *, key: str, at: str) -> dict: ...
    def decide(self, identifier: str, *, decision: str, reason: str, expected_revision: int, key: str, at: str) -> dict: ...
    def resolve_report(self, source: str, identifier: str) -> dict: ...
    def identity_candidates(self, query: str) -> dict: ...
