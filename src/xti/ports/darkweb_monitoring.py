"""Small ports for P05 stored-source monitoring and authenticated domain search."""

from typing import Protocol


class DarkwebInputs(Protocol):
    def capture(self, profile: dict, at: str) -> dict: ...


class CredentialDomainSource(Protocol):
    def fetch(self, domain: str, api_key: str) -> dict: ...


class CredentialSecrets(Protocol):
    def readiness(self, organization_id: str) -> dict: ...
    def api_key(self) -> str: ...
    def identity_key(self, organization_id: str) -> bytes: ...
    def save_api_key(self, value: str): ...
    def create_identity_key(self, organization_id: str): ...


class PasswordExposureSource(Protocol):
    def check_password(self, password: str) -> dict: ...


class DomainExposureSource(Protocol):
    def fetch(self, domain: str) -> dict: ...


class DarkwebRepository(Protocol):
    def read(self, operation: str, values: dict) -> dict: ...
    def mutate(self, operation: str, values: dict, at: str) -> dict: ...
    def plan(self, identifier: str) -> dict: ...
    def replay(self, values: dict) -> dict | None: ...
    def reserve(self, values: dict, snapshot: dict, at: str) -> tuple[dict, bool]: ...
    def finish(self, run_id: str, analysis: dict, at: str) -> dict: ...
    def fail(self, run_id: str, code: str, at: str) -> None: ...
    def credential_plan(self, identifier: str, domain: str) -> dict: ...
    def credential_replay(self, plan: dict, request_key: str) -> dict | None: ...
    def reserve_credentials(self, plan: dict, request_key: str, at: str) -> tuple[dict, bool]: ...
    def finish_credentials(self, run_id: str, response: dict, records: list[dict],
                           at: str) -> dict: ...
    def fail_credentials(self, run_id: str, code: str, message: str, at: str) -> dict: ...
    def source_plan(self, identifier: str, provider: str, domain: str | None = None) -> dict: ...
    def source_replay(self, operation: str, values: dict) -> dict | None: ...
    def reserve_source(self, operation: str, values: dict, plan: dict, metadata: dict,
                       at: str) -> tuple[dict, bool]: ...
    def finish_source(self, run_id: str, response: dict, at: str) -> dict: ...
    def fail_source(self, run_id: str, code: str, message: str, at: str) -> dict: ...
