"""Acquisition and persistence boundaries for reference context."""
from typing import Protocol
from xti.domain.warninglists import WarninglistRun, WarninglistSnapshot, WarninglistState


class WarninglistSource(Protocol):
    def resolve_revision(self) -> str: ...
    def fetch(self, list_id: str, revision: str) -> bytes: ...


class WarninglistRepository(Protocol):
    def record(self, list_id: str, *, revision: str | None, started_at: str,
               finished_at: str, content: bytes | None, error: str | None) -> WarninglistRun: ...
    def read(self) -> tuple[WarninglistState, ...]: ...
    def history(self, list_id: str, *, offset: int, limit: int) -> tuple[WarninglistRun, ...]: ...
    def show(self, run_id: str) -> tuple[WarninglistRun, WarninglistSnapshot | None]: ...
