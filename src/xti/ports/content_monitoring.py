"""Ports for workspace-local content monitoring and separately authenticated sources."""
from typing import Protocol


class ContentRepository(Protocol):
    def read(self, operation: str, values: dict) -> dict: ...
    def mutate(self, operation: str, values: dict, at: str, *, bindings: dict | None = None) -> dict: ...
    def reserve(self, values: dict, at: str, *, bindings: dict) -> tuple[dict, bool]: ...
    def finish(self, identifier: str, result: dict, at: str) -> dict: ...
    def replay_run(self, values: dict) -> dict | None: ...
    def replay_mutation(self, operation: str, values: dict) -> dict | None: ...
    def previous_targets(self, watch_id: str, source_id: str, native_id: str) -> set[tuple[str, str]]: ...


class ContentSources(Protocol):
    def status(self) -> list[dict]: ...
    def collect(self, source: dict, checkpoint: dict, budget: dict, consume, *, targets=()) -> dict:
        """Bounded source window. Callback consumes one ContentDocument; no secret/raw body logs."""
        ...
