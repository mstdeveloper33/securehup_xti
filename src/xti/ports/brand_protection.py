"""Ports for brand collection and immutable comparison/review storage."""
from typing import Protocol


class BrandProtectionSources(Protocol):
    def status(self) -> dict: ...
    def collect(self, snapshot: dict, retained: list[dict], *, cancelled) -> dict: ...


class BrandProtectionRepository(Protocol):
    def read(self, operation: str, values: dict) -> dict: ...
    def mutate(self, operation: str, values: dict, at: str) -> dict: ...
    def reserve(self, values: dict, at: str) -> tuple[dict, bool]: ...
    def retained(self, watch_id: str, limit: int, after: int) -> dict: ...
    def finish(self, run_id: str, result: dict, at: str) -> dict: ...
