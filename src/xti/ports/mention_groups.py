"""Small durable boundary for group definitions, reservations and result receipts."""

from typing import Protocol
from xti.domain.mentions import MentionRequest
from xti.domain.mention_groups import (
    MentionGroup, MentionGroupDefinition, MentionGroupRun, MentionGroupOperation,
    MentionGroupBudget,
)


class MentionGroupRepository(Protocol):
    def save(self, name: str, definition: MentionGroupDefinition, *, recorded_at: str) -> MentionGroup: ...
    def disable(self, identifier: str, *, reason: str, recorded_at: str) -> MentionGroup: ...
    def get(self, identifier: str) -> MentionGroup: ...
    def list(self, *, active_only: bool = True) -> tuple[MentionGroup, ...]: ...
    def budget(self, identifier: str, *, at: str) -> MentionGroupBudget: ...
    def begin(self, identifier: str, requests: tuple[MentionRequest, ...], *, started_at: str,
              request_id: str | None = None) -> MentionGroupRun: ...
    def reserve_attempt(self, run_id: str, index: int, *, started_at: str) -> MentionGroupOperation: ...
    def recover(self, run_id: str, *, recorded_at: str) -> MentionGroupRun: ...
    def skip_pending(self, run_id: str, *, reason: str, recorded_at: str) -> MentionGroupRun: ...
    def record_notification(self, run_id: str, index: int, *, notification_run_id: str,
                            recorded_at: str) -> MentionGroupRun: ...
    def finish(self, run_id: str, *, finished_at: str) -> MentionGroupRun: ...
    def find_run(self, run_id: str) -> MentionGroupRun | None: ...
    def run_show(self, run_id: str) -> MentionGroupRun: ...
    def runs(self, identifier: str) -> tuple[MentionGroupRun, ...]:
        """Return immutable runs in original, oldest-first creation order."""
        ...
