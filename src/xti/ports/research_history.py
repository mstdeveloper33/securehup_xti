"""Workspace-bound immutable review persistence; no provider operations."""
from typing import Protocol
from xti.domain.research_history import ReviewHeader, StoredReview


class ResearchHistoryRepository(Protocol):
    def find_key(self, key: str) -> StoredReview | None: ...
    def latest(self, scope: dict) -> ReviewHeader | None: ...
    def append(self, scope: dict, snapshot: dict, key: str, expected_previous: str | None) -> tuple[StoredReview, bool]: ...
    def show(self, review_id: str) -> StoredReview: ...
    def history(self, indicator_type: str, value: str, *, offset: int, limit: int, expected_snapshot: str | None) -> dict: ...
