"""Small persistence and process boundaries for managed work."""

from collections.abc import Callable
from typing import Protocol
from xti.domain.nmap_execution import NmapWork
from xti.domain.nmap_management import ManagedNmapPlan


class NmapWorkRepository(Protocol):
    def create(self, plan: ManagedNmapPlan, key: str, at: str) -> NmapWork: ...
    def find_request(self, asset_id: str, key: str) -> NmapWork | None: ...
    def get(self, asset_id: str, job_id: str) -> NmapWork: ...
    def list(self, asset_id: str, *, limit: int = 20, offset: int = 0) -> tuple[NmapWork, ...]: ...
    def append(self, work: NmapWork, kind: str, payload: dict, at: str, *, token: str | None) -> NmapWork: ...
    def cancelled(self, asset_id: str, job_id: str) -> bool: ...
    def check_binding(self, work: NmapWork) -> None: ...


class ManagedNmapRunner(Protocol):
    def readiness(self, plan: ManagedNmapPlan) -> dict: ...
    def run(self, plan: ManagedNmapPlan, address: str, *, should_stop: Callable[[], bool],
            lock_fd: int, duration_seconds: float) -> dict: ...
