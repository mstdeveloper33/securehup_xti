"""External acquisition and workspace storage ports."""
from typing import Protocol
from xti.domain.indicator_enrichment import EnrichmentQuery, EnrichmentRun, EnrichmentState, EnrichmentSnapshot


class EnrichmentSource(Protocol):
    def fetch(self, query: EnrichmentQuery) -> tuple[int, bytes]: ...


class EnrichmentRepository(Protocol):
    def record(self, query: EnrichmentQuery, *, started_at: str, finished_at: str,
               http_status: int | None, content: bytes | None, error: str | None) -> EnrichmentRun: ...
    def read(self, query: EnrichmentQuery) -> EnrichmentState: ...
    def history(self, query: EnrichmentQuery, *, offset: int, limit: int) -> tuple[EnrichmentRun, ...]: ...
    def show(self, run_id: str) -> tuple[EnrichmentRun, EnrichmentSnapshot | None]: ...
