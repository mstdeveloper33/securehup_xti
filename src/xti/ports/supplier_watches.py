"""Small supplier watch configuration and historical read contract."""
from typing import Protocol
from xti.domain.supplier_watches import SupplierWatchMutation, SupplierWatchPage, SupplierWatchDetails, SupplierWatchRunReport


class SupplierWatchRepository(Protocol):
    def configure(self, supplier_id: str, *, source: str, enabled: bool, reason: str, recorded_at: str) -> SupplierWatchMutation: ...
    def list(self, *, active_only: bool, offset: int, limit: int) -> SupplierWatchPage: ...
    def show(self, watch_id: str, *, event_limit: int, run_limit: int, event_offset: int, run_offset: int) -> SupplierWatchDetails: ...
    def run_show(self, run_id: str, *, item_limit: int, offset: int) -> SupplierWatchRunReport: ...
