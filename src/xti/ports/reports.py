"""Workspace-bound report persistence and one-snapshot evidence read."""

from typing import Protocol
from xti.domain.ioc_lifecycle import IocLifecycleSnapshot


class ReportRepository(Protocol):
    def mutate(self, operation: str, request: dict, at: str) -> dict: ...
    def read(self) -> dict: ...
    def evidence(self, indicator_type: str, value: str) -> tuple[dict, IocLifecycleSnapshot]: ...
    def fetch_replay(self, request: dict) -> dict | None: ...
    def record_fetch(self, request: dict, fetched, error: str | None, at: str) -> dict: ...
    def fetches(self) -> list[dict]: ...
