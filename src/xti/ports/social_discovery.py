"""Small boundaries for collection, public-page checks, and durable receipts."""
from typing import Protocol
from xti.domain.social_discovery import Page


class PublicProfilePages(Protocol):
    def fetch(self, url: str, *, allowed_hosts: tuple[str, ...], timeout: float) -> Page: ...


class SocialDiscoverySources(Protocol):
    def collect(self, source: str, username: str, platforms: tuple[str, ...], *, timeout: int, remaining: float) -> dict: ...
    def search(self, scope: dict, *, remaining: float) -> tuple[dict, ...]: ...


class SocialDiscoveryRepository(Protocol):
    def reserve(self, scope: dict, key: str, at: str) -> dict: ...
    def finish(self, identifier: str, report: dict, at: str) -> dict: ...
    def show(self, identifier: str) -> dict: ...
    def list(self, *, domain: str | None = None, offset: int = 0, limit: int = 20) -> dict: ...
    def known_links(self, domain: str) -> tuple[str, ...]: ...
