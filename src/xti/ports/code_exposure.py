"""Narrow integration ports; implementations own network and persistence details."""
from typing import Protocol
from xti.domain.code_exposure import Document


class CodeRepository(Protocol):
    def read(self, operation: str, parameters: dict) -> dict: ...
    def mutate(self, operation: str, parameters: dict, at: str) -> dict: ...
    def reserve(self, parameters: dict, at: str) -> tuple[dict, bool]: ...
    def finish(self, identifier: str, result: dict, at: str) -> dict: ...


class CodeSource(Protocol):
    def status(self) -> list[dict]: ...
    def collect(self, scope: dict, checkpoints: dict, consume) -> dict:
        """Call consume(Document) once for each bounded text document; never retain bodies."""
        ...


class SecretScanner(Protocol):
    def status(self) -> dict: ...
    def scan(self, content: str, *, seconds: float) -> list[dict]: ...
