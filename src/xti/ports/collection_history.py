"""Durable collection history; source result receipts remain inside source transactions."""
from typing import Protocol
from xti.domain.collection_profiles import CollectionProfile
from xti.domain.collection_history import (
    CollectionFrozenPlan, CollectionOperationToken, CollectionProfileOrigin,
    CollectionResumePlan, CollectionSessionDetails, CollectionSessionPage,
)

class CollectionHistoryRepository(Protocol):
    def profile_origin(self, profile: CollectionProfile) -> CollectionProfileOrigin: ...
    def begin(self, plan: CollectionFrozenPlan, *, started_at: str, parent_id: str | None = None) -> CollectionSessionDetails: ...
    def resume_plan(self, session_id: str) -> CollectionResumePlan: ...
    def start_step(self, session_id: str, step_id: str, *, started_at: str) -> CollectionOperationToken: ...
    def stop_step_without_result(self, token: CollectionOperationToken, *, status: str, error_code: str, finished_at: str) -> None: ...
    def finish_session(self, session_id: str, *, analysis_status: str, finished_at: str, stop_reason: str | None = None) -> CollectionSessionDetails: ...
    def recover_interrupted(self, *, recorded_at: str, reason: str = "recovered") -> tuple[str, ...]: ...
    def get(self, session_id: str) -> CollectionSessionDetails: ...
    def list(self, *, limit: int = 50, before: int | None = None) -> CollectionSessionPage: ...
