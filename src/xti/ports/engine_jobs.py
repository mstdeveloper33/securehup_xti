"""Small queue and saved-profile execution ports for platform engine jobs."""

from collections.abc import Callable
from typing import Protocol

from xti.domain.engine_jobs import EngineJob, EngineJobClaim, EngineJobPayload
from xti.domain.source_jobs import SourceJobPayload


class EngineJobRepository(Protocol):
    def find_request(self, key: str) -> EngineJob | None: ...
    def create(self, key: str, request: str, payload: EngineJobPayload | SourceJobPayload, *, recorded_at: str) -> EngineJob: ...
    def get(self, job_id: str) -> EngineJob: ...
    def claim(self, job_id: str | None, *, recorded_at: str) -> EngineJobClaim | None: ...
    def link_session(self, claim: EngineJobClaim, session_id: str, *, recorded_at: str) -> None: ...
    def finish(self, claim: EngineJobClaim, *, status: str, result: dict | None,
               error_code: str | None, recorded_at: str) -> EngineJob: ...
    def cancel(self, job_id: str, *, recorded_at: str) -> EngineJob: ...
    def source_step(self, claim, key, *, action, recorded_at, receipt=None, reason=None) -> EngineJob: ...
    def list_sources(self, *, limit=20, offset=0) -> tuple[tuple[EngineJob, ...], bool]: ...
    def recover_interrupted(self, *, recorded_at: str) -> tuple[EngineJob, ...]:
        """Caller holds the same exclusive worker lock as work_one; never requeue."""
        ...


class EngineJobRunner(Protocol):
    def prepare(self, profile_name: str, profile_revision: int) -> EngineJobPayload: ...
    def run(self, payload: EngineJobPayload, *, session_started: Callable[[str], None]) -> dict: ...


class JobHistoryRepository(Protocol):
    def history(self, *, bucket, limit, before_sequence, expected_snapshot) -> dict: ...
    def capacity(self) -> dict: ...
    def validate(self) -> dict: ...


class SourceJobOperations(Protocol):
    def execute(self, key: str, plan: dict, job_id: str, *, measure: bool = False) -> dict: ...
    def verify(self, key: str, receipt: dict, plan: dict) -> None: ...


class SourceJobRunner(Protocol):
    def run(self, job: EngineJob, *, started, current, progress) -> dict: ...
